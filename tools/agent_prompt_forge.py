#!/usr/bin/env python3
"""Rewrite each web subagent's prompt from what this tree has actually measured.

An agent definition written by hand is a role description. It ages the moment a
solve lands, because the thing a solve produces -- a chain card with its
`known_traps`, its `first_confirming_probe` and its `blast_radius` -- never
reaches the agent that would need it next. Measured on this tree: 70 chain cards
carry 403 traps between them, and not one of those sentences appeared in any
subagent prompt.

So this tool forges a MANAGED block into each `.claude/agents/ctf-web-*.md`,
built from the cards and field notes of the bug classes that agent owns, and
refreshes it after every solve. The hand-written part of each file is never
touched: only the text between the two markers is replaced.

    python3 tools/agent_prompt_forge.py --apply
    python3 tools/agent_prompt_forge.py --check            # the gate's form
    python3 tools/agent_prompt_forge.py --from-solve <id>  # after a flag

Class ownership is not restated here. It is read from `WEB_FAMILIES` in
tools/subagent_fanout.py, which is the same table `--web` builds its briefs from,
so the two can never disagree about which agent owns which class.
"""
import argparse
import glob
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import subagent_fanout as fanout  # noqa: E402  -- the family table lives there

AGENTS = os.path.join(ROOT, ".claude", "agents")
CHAINS = os.path.join(ROOT, "knowledge", "chains")
SKILLS = os.path.join(ROOT, "skills")
TAXONOMY = os.path.join(ROOT, "knowledge", "bug-classes.json")
BEGIN = "<!-- FORGED:BEGIN — regenerated by tools/agent_prompt_forge.py, do not hand-edit -->"
END = "<!-- FORGED:END -->"
MAX_TRAPS = 12
MAX_PROBES = 4


def load_cards():
    out = []
    for path in sorted(glob.glob(os.path.join(CHAINS, "*.json"))):
        try:
            with open(path, encoding="utf-8") as fh:
                card = json.load(fh)
        except (OSError, ValueError):
            continue
        card["_file"] = os.path.relpath(path, ROOT)
        out.append(card)
    return out


def cards_for(classes, cards, tax=None):
    """Cards this family owns, by BOTH links, because neither alone is complete.

    A card's own `classification.primary` is one link. The taxonomy's
    `verified_by` list is the other, and it is the authoritative one -- that is
    where a class records which cards prove it. Measured on this tree: 5 of the
    cards that `verified_by` names for file-read, upload and XXE carry
    `classification: {"primary": null}`, so filtering on primary alone found
    ZERO cards for ctf-web-files while the taxonomy said those classes were
    verified. Union the two and the family gets its own evidence.

    A card that merely ALSO-matched a class is still excluded: it did not open
    its chain there, and filing its traps under that class is how a skill fills
    up with another family's lessons.
    """
    want = set(classes)
    named = set()
    for cid in want:
        for card_id in ((tax or {}).get(cid) or {}).get("verified_by") or []:
            named.add(card_id)
    hits, seen = [], set()
    for card in cards:
        cl = card.get("classification") or {}
        if (cl.get("primary") in want or card.get("id") in named) and card["id"] not in seen:
            seen.add(card["id"])
            hits.append(card)
    return hits


def taxonomy():
    try:
        with open(TAXONOMY, encoding="utf-8") as fh:
            return {c["id"]: c for c in json.load(fh)["classes"]}
    except (OSError, ValueError, KeyError):
        return {}


def confirmed_notes(classes):
    """Field notes an operator has promoted from proposed to confirmed."""
    out = []
    for cid in classes:
        path = os.path.join(SKILLS, cid, "field-notes.md")
        if not os.path.isfile(path):
            continue
        with open(path, encoding="utf-8") as fh:
            text = fh.read()
        # a note block is a heading followed by its body; keep only confirmed ones
        for block in re.split(r"\n(?=## )", text):
            if re.search(r"^- status: confirmed\s*$", block, re.M):
                head = block.splitlines()[0].lstrip("# ").strip()
                body = " ".join(l.strip() for l in block.splitlines()[1:]
                                if l.strip() and not l.startswith("- "))
                if head:
                    out.append((cid, head, body[:300]))
    return out


def forge(family, cards, tax):
    classes = family["classes"]
    mine = cards_for(classes, cards, tax)
    lines = [BEGIN, ""]
    lines.append("## What this tree has measured about your own classes")
    lines.append("")
    lines.append("You are the specialist for this family. The material below is not general")
    lines.append("knowledge: every line was produced by a solve or a measurement in this")
    lines.append("repository, and each is attributed so you can open the source and check it.")
    lines.append("Prefer it over anything you recall.")
    lines.append("")

    ev = []
    for cid in classes:
        cls = tax.get(cid) or {}
        lvl = cls.get("evidence_level", "?")
        n = len(cls.get("verified_by") or [])
        ev.append("`%s` **%s**%s" % (cid, lvl, (" (%d card%s)" % (n, "" if n == 1 else "s")) if n else ""))
    if ev:
        lines.append("**Your classes:** " + " · ".join(ev) + ".")
        lines.append("A **catalogue** class has never been solved here — say so rather than")
        lines.append("presenting its technique as local experience.")
        lines.append("")

    if not classes:
        # recon and bundle serve SKILLS, not taxonomy classes -- measured: neither
        # web-info-disclosure nor web-source-map is a class in bug-classes.json,
        # so there is no verified_by list and no card to inherit. Say that rather
        # than emitting an empty section that reads like missing data.
        lines.append("**This family owns no taxonomy bug class.** Its subject is covered by")
        lines.append("skills rather than by a class, so there is no `evidence_level` and no")
        lines.append("`verified_by` list for it anywhere — do not claim one.")
        lines.append("")
        for sk in family.get("skills") or []:
            lines.append("- `%s`" % sk)
        lines.append("")
        lines.append("Your job is breadth at one point in time: produce the inventory every")
        lines.append("other family probes against, and mark what you did NOT cover so a full")
        lines.append("report is never mistaken for full coverage.")
        lines.append("")
    elif not mine:
        lines.append("**No chain card in this repository backs this family.**")
        lines.append("That is the honest state: you are working from published technique, not")
        lines.append("from local experience. Record what you measure so the next run is not.")
        lines.append("")
    else:
        lines.append("### First probes that actually opened a chain here")
        lines.append("")
        for card in mine[:MAX_PROBES]:
            fp = card.get("first_confirming_probe") or {}
            req = (fp.get("request") or "").strip().replace("\n", " ")
            exp = (fp.get("expected") or "").strip().replace("\n", " ")
            if not req:
                continue
            lines.append("- **%s** — `%s`" % (card["id"], req[:200]))
            if exp:
                lines.append("  expected: %s" % exp[:220])
        lines.append("")

        traps, seen = [], set()
        for card in mine:
            for t in (card.get("known_traps") or []):
                key = t[:60]
                if key in seen:
                    continue
                seen.add(key)
                traps.append((card["id"], t))
        if traps:
            lines.append("### Traps this tree has already paid for")
            lines.append("")
            for cid, t in traps[:MAX_TRAPS]:
                lines.append("- %s  *(%s)*" % (t.strip().replace("\n", " ")[:300], cid))
            if len(traps) > MAX_TRAPS:
                lines.append("")
                lines.append("*%d more in the cards above; open the card before working its chain.*"
                             % (len(traps) - MAX_TRAPS))
            lines.append("")

        br = [(c["id"], c.get("blast_radius")) for c in mine if c.get("blast_radius")]
        if br:
            lines.append("### Blast radius recorded for this family")
            lines.append("")
            for cid, b in br[:3]:
                lines.append("- %s  *(%s)*" % (str(b).replace("\n", " ")[:280], cid))
            lines.append("")

    notes = confirmed_notes(classes)
    if notes:
        lines.append("### Confirmed field notes")
        lines.append("")
        for cid, head, body in notes[:6]:
            lines.append("- **%s** (`%s`) — %s" % (head[:110], cid, body[:200]))
        lines.append("")

    lines.append("*%d card%s, %d trap%s, %d confirmed note%s.*" % (
        len(mine), "" if len(mine) == 1 else "s",
        sum(len(c.get("known_traps") or []) for c in mine),
        "" if sum(len(c.get("known_traps") or []) for c in mine) == 1 else "s",
        len(notes), "" if len(notes) == 1 else "s"))
    lines.append("")
    lines.append(END)
    return "\n".join(lines)


def apply_to(path, block):
    with open(path, encoding="utf-8") as fh:
        text = fh.read()
    if BEGIN in text and END in text:
        new = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END), block, text, flags=re.S)
    else:
        new = text.rstrip("\n") + "\n\n" + block + "\n"
    return new, new != text


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    g = ap.add_mutually_exclusive_group(required=True)
    g.add_argument("--apply", action="store_true", help="rewrite the managed blocks")
    g.add_argument("--check", action="store_true",
                   help="exit non-zero if any block is stale; the gate's form")
    g.add_argument("--from-solve", metavar="CHAIN_ID",
                   help="refresh only the families whose classes that card belongs to")
    a = ap.parse_args()

    cards = load_cards()
    tax = taxonomy()
    only = None
    if a.from_solve:
        card = next((c for c in cards if c["id"] == a.from_solve), None)
        if not card:
            print(json.dumps({"error": "no such chain card", "id": a.from_solve}),
                  file=sys.stderr)
            return 2
        only = (card.get("classification") or {}).get("primary")

    report, stale = [], []
    for family in fanout.WEB_FAMILIES:
        path = os.path.join(AGENTS, family["agent"] + ".md")
        if not os.path.isfile(path):
            report.append({"agent": family["agent"], "skipped": "no definition on disk"})
            continue
        if only and only not in family["classes"]:
            continue
        block = forge(family, cards, tax)
        new, changed = apply_to(path, block)
        owned = cards_for(family["classes"], cards, tax)
        n_cards = len(owned)
        row = {"agent": family["agent"], "classes": len(family["classes"]),
               "cards": n_cards,
               "traps": sum(len(c.get("known_traps") or []) for c in owned),
               "changed": changed}
        report.append(row)
        if changed:
            stale.append(family["agent"])
            if a.apply or a.from_solve:
                with open(path, "w", encoding="utf-8") as fh:
                    fh.write(new)

    unclassified = [c["id"] for c in cards
                    if not (c.get("classification") or {}).get("primary")]
    out = {"cards_with_no_primary_classification": len(unclassified),
           "mode": "check" if a.check else ("from-solve" if a.from_solve else "apply"),
           "from_solve": a.from_solve, "agents": report,
           "stale": stale,
           "note": "the hand-written part of each definition is never touched; only the "
                   "text between the FORGED markers is replaced"}
    print(json.dumps(out, indent=2, ensure_ascii=False))
    if a.check and stale:
        print("STALE: %s -- run tools/agent_prompt_forge.py --apply" % ", ".join(stale),
              file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
