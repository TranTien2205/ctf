#!/usr/bin/env python3
"""Regenerate skills/registry.json from the SKILL.md frontmatter."""
from __future__ import annotations

import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SKILLS = ROOT / "skills"
WORKFLOW_SKILLS = {"blackbox-web", "orchestration"}
META_SKILLS = {"extending-argus", "report-writing"}


def main() -> int:
    entries = []
    for directory in sorted(SKILLS.iterdir()):
        path = directory / "SKILL.md"
        if not path.is_file():
            continue
        text = path.read_text(encoding="utf-8")
        name = re.search(r"^name:\s*(.+)$", text, re.M)
        description = re.search(r"^description:\s*(.+)$", text, re.M)
        classes = re.search(r"^classes:\s*(.+)$", text, re.M)
        if not name or not description:
            print(f"{path}: missing name or description in the frontmatter", file=sys.stderr)
            return 1
        entries.append({
            "name": name.group(1).strip(),
            "path": f"skills/{directory.name}/SKILL.md",
            "kind": "workflow" if directory.name in WORKFLOW_SKILLS else
                    ("meta" if directory.name in META_SKILLS else "class"),
            "summary": description.group(1).strip()[:200],
            "classes": [item.strip() for item in classes.group(1).split(",")] if classes else [],
            "lines": len(text.splitlines()),
        })
    (SKILLS / "registry.json").write_text(
        json.dumps({"version": 1,
                    "note": "Generated by scripts/gen_skill_registry.py. One router skill "
                            "(blackbox-web), one depth skill at a time.",
                    "skills": entries}, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"{len(entries)} skills registered")
    return 0


if __name__ == "__main__":
    sys.exit(main())
